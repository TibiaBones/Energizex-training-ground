// Параметры (все, кроме visibleCount, обязательны):
//   products     - массив объектов товаров (каждый с полями id, name, currentPrice, ...)
//   containerId  - id внешнего контейнера (с overflow:hidden) – это "окно"
//   trackId      - id внутренней обёртки (с display:flex) – её будем двигать
//   prevBtnId    - id кнопки "Назад"
//   nextBtnId    - id кнопки "Вперед"
//   indicatorId  - id элемента, куда писать "1 / 10", скорее всего выкину
//   visibleCount - сколько карточек полностью помещается в окне (по умолчанию 4)
function createCarousel(products, containerId, trackId, prevBtnId, nextBtnId, indicatorId, visibleCount = 4) {
    const container = document.getElementById(containerId); // внешний блок (окно)
    const track = document.getElementById(trackId);         // внутренняя полоса (двигается)
    const prevBtn = document.getElementById(prevBtnId);     // кнопка "Назад"
    const nextBtn = document.getElementById(nextBtnId);     // кнопка "Вперед"
    const indicator = document.getElementById(indicatorId); // индикатор
    // !!!!!!!!!!!!!!!!!!!!реализовать индикатор, продумать как можно изменить расстояние, на которое отматывается трэк при нажатии на кнопку!!!!!!!!!!!!!!!!

    if (!container || !track || !prevBtn || !nextBtn) {
        console.error('Ошибка: не найден один из элементов карусели', {
            containerId, trackId, prevBtnId, nextBtnId, indicatorId
        });
        return;
    }
    

    track.innerHTML = products.map(item => {
        // проверка на наличие скидки (убедиться что нынешняя цена не равняется первоначальной, убеждаемся что есть скидка)
        const hasDiscount = item.discount && item.originalPrice && item.originalPrice !== item.currentPrice
        // убеждаемся что товар из категории bestseller, нужно логическое значение
        const sectionTest = item.storeSection == 'bestseller'; 
        
        return `
        <div class="cardContainer">
            <div class="cardTagDiscountLikePanel" data-product-id="${item.id}">
                <div class="cardTagDiscountContainer">
                    ${sectionTest ? `<span class="cardTag">bestseller</span>` : ''}
                    ${hasDiscount ? `<div class="cardDiscount">${item.discount}</div>` : ''}
                </div>

                <button class="cardLike">
                    <svg width="20" height="20">
                        <use href="#likeSvg" />
                    </svg>
                </button>
            </div>

            <button class="cardAddButton">
                <span class="cardAddButtonText">Add to cart</span>
            </button>

            <div class="cardImgContainer">
                <img src="${item.imgSrc}" alt="${item.name}" class="cardImg" />
            </div>

            <div class="cardInfoContainer">
                <div class="cardGrade">
                    <svg width="16" height="16">
                        <use href="#starIconSvg"></use>
                    </svg>

                    <svg width="16" height="16">
                        <use href="#starIconSvg"></use>
                    </svg>

                    <svg width="16" height="16">
                        <use href="#starIconSvg"></use>
                    </svg>

                    <svg width="16" height="16">
                        <use href="#starIconSvg"></use>
                    </svg>

                    <svg width="16" height="16">
                        <use href="#starIconSvg"></use>
                    </svg>
                </div>

                <span class="cardName">${item.name}</span>

                <div class="cardPriseContainer">
                    <span class="cardCurrentPrice">&#8377 ${item.currentPrice.toFixed(2)}</span>

                    ${hasDiscount ? `<span class="cardOriginalPrise">&#8377 <span
                                    style="text-decoration: line-through;">${item.currentPrice.toFixed(2)}</span></span>` : ''}
                </div>
            </div>
        </div>                   
        `;
    }).join('');

    let currentIndex = 0; //текущий индекс

    const totalItems = products.length; //общее количество карточек

    const firstCard = track.querySelector('.cardContainer'); //получаем первую карточку, выводим ошибку если карточек вообще нет
    if (!firstCard) {
        console.error('Нет ни одной карточки в треке');
        return;
    }

    const cardWidth = firstCard.offsetWidth;
    const gap = parseFloat(getComputedStyle(track).gap) || 0;
    const step = cardWidth + gap;
    const maxIndex = Math.max(0, totalItems - visibleCount); // максимальный индекс, наколько можно сдвинуться чтобы не уехать за экран 

    //функция отрисовки и обновления карусели
    // Если анимация не нужна (первая отрисовка) – убираем transition на время
    function updateCarousel(animate = true) {
        if (!animate) {
            track.style.transition = 'none';
        } else {
            track.style.transition = 'transform 0.4s ease';
        }

        track.style.transform = `translateX(-${currentIndex * cardWidth}px)` // сдвигаем трек влево 

        //если буду делать индикатор, то нужно его обновление вставить тут

        //обновление состояния кнопок, тернарный оператор офигенный вариант вместо длинных блоков if\else
        prevBtn.style.display = (currentIndex === 0) ? 'none' : 'block';
        nextBtn.style.display = (currentIndex >= maxIndex) ? 'none' : 'block';

        //вот тут в дальнейшем разобраться с анимацией
        // Если анимацию отключали – включаем обратно для следующих кликов
        if (!animate) {
            // Принудительно пересчитываем стили, чтобы transition применился (нужно из-за встроенного поведения жабаскрипта)
            track.offsetHeight;
            track.style.transition = 'transform 0.4s ease';
        }
    }

    //Обработчики кликов по кнопкам
    prevBtn.addEventListener('click', function () {
        if (currentIndex > 0) {
            currentIndex--;
            updateCarousel(true); // с анимацией
        }
    });

    nextBtn.addEventListener('click', function () {
        if (currentIndex < maxIndex) {
            currentIndex++;
            updateCarousel(true); // с анимацией
        }
    });

    //Первоначальная отрисовка без анимации
    updateCarousel(false);
}
